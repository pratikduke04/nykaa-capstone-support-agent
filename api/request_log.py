"""
Task 12 - structured JSON-Lines request logging (ELK-style: one JSON object per line).

Every entry carries a @timestamp, a trace_id and timing. PII safety is enforced TWICE:
  1. callers pass the already-masked question, and
  2. log_request() runs the same mask_pii() used for the model over every string it writes,
     so a fixed-format PII value (phone, card last-4) can never reach disk in the clear.
"""
import json
import os
import threading
from datetime import datetime, timezone
from pathlib import Path

from crew.guardrails import mask_pii

LOG_PATH = Path(os.environ.get("REQUEST_LOG_PATH",
                               Path(__file__).resolve().parent.parent / "logs" / "requests.jsonl"))

# Ids generated by the server itself (random hex) can never hold customer PII, and the phone
# regex would wrongly mangle a hex id such as "7b98765432..." - so they are left untouched.
SAFE_KEYS = {"trace_id", "connection_id"}

_lock = threading.Lock()


def scrub(value):
    """Recursively mask PII in every string inside a log record."""
    if isinstance(value, str):
        return mask_pii(value)[0]
    if isinstance(value, dict):
        return {k: (v if k in SAFE_KEYS else scrub(v)) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [scrub(v) for v in value]
    return value


def log_request(entry: dict) -> None:
    record = {"@timestamp": datetime.now(timezone.utc).isoformat(timespec="milliseconds"), **scrub(entry)}
    line = json.dumps(record, ensure_ascii=False, default=str)
    with _lock:
        LOG_PATH.parent.mkdir(parents=True, exist_ok=True)
        with LOG_PATH.open("a", encoding="utf-8") as f:
            f.write(line + "\n")